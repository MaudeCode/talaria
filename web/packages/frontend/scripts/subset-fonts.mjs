// TAL-1709: split InterVariable into the per-script subsets Google Fonts serves for Inter, so a page downloads only
// the unicode ranges it renders. Writes src/theme/fonts/generated/ (gitignored): one woff2 per subset and inter.css,
// the @font-face rules keyframes.css imports. Both variation axes (opsz, wght) stay.
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import fontverter from 'fontverter'
import subsetFont from 'subset-font'

const srcDir = resolve(import.meta.dirname, '../src')
const fontsDir = resolve(srcDir, 'theme/fonts')
const source = resolve(fontsDir, 'InterVariable.woff2')
const outDir = resolve(fontsDir, 'generated')
const css = resolve(outDir, 'inter.css')

// The unicode-range of each subset in fonts.googleapis.com/css2?family=Inter, minus greek-ext (polytonic Greek falls
// back to the system face).
export const subsets = {
  'cyrillic-ext': 'U+0460-052F, U+1C80-1C8A, U+20B4, U+2DE0-2DFF, U+A640-A69F, U+FE2E-FE2F',
  cyrillic: 'U+0301, U+0400-045F, U+0490-0491, U+04B0-04B1, U+2116',
  greek: 'U+0370-0377, U+037A-037F, U+0384-038A, U+038C, U+038E-03A1, U+03A3-03FF',
  vietnamese: 'U+0102-0103, U+0110-0111, U+0128-0129, U+0168-0169, U+01A0-01A1, U+01AF-01B0, U+0300-0301, U+0303-0304, U+0308-0309, U+0323, U+0329, U+1EA0-1EF9, U+20AB',
  'latin-ext': 'U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, U+0308, U+0329, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C0, U+2113, U+2C60-2C7F, U+A720-A7FF',
  latin: 'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD',
}

export const subsetFile = (name) => resolve(outDir, `InterVariable-${name}.woff2`)

/** Every code point a unicode-range covers, as the text harfbuzz subsets to. */
function rangeText(range) {
  let text = ''
  for (const part of range.split(',')) {
    const [start, end = start] = part.trim().replace(/^U\+/, '').split('-').map((hex) => parseInt(hex, 16))
    for (let codePoint = start; codePoint <= end; codePoint++) text += String.fromCodePoint(codePoint)
  }
  return text
}

/** An uncompressed sfnt of the font, with its table offsets by tag. */
export async function fontTables(font) {
  const sfnt = await fontverter.convert(font, 'truetype')
  const tables = new Map()
  for (let i = 0; i < sfnt.readUInt16BE(4); i++) tables.set(sfnt.toString('latin1', 12 + i * 16, 16 + i * 16), sfnt.readUInt32BE(20 + i * 16))
  return { sfnt, tables }
}

/** The font's OpenType feature tags (GSUB and GPOS FeatureLists). */
export async function featureTags(woff2) {
  const { sfnt: font, tables } = await fontTables(woff2)
  const tags = new Set()
  for (const [table, offset] of tables) {
    if (table !== 'GSUB' && table !== 'GPOS') continue
    const list = offset + font.readUInt16BE(offset + 6)
    for (let i = 0; i < font.readUInt16BE(list); i++) tags.add(font.toString('latin1', list + 2 + i * 6, list + 6 + i * 6))
  }
  return tags
}

/** Feature tags the app's styles turn on with font-feature-settings. */
function enabledFeatures() {
  const tags = new Set()
  for (const file of readdirSync(srcDir, { recursive: true })) {
    if (!/\.(css|tsx?)$/.test(file) || file.startsWith('theme/fonts/generated')) continue
    for (const [, value] of readFileSync(resolve(srcDir, file), 'utf8').matchAll(/font-?feature-?settings\s*:\s*([^;}]+)/gi)) {
      for (const [, tag] of value.matchAll(/["'](\w{4})["']/g)) tags.add(tag)
    }
  }
  return [...tags].sort()
}

/**
 * Every feature a CSS property can reach stays. Inter's opt-in stylistic alternates (cvNN, ssNN, salt, aalt) pull a
 * second copy of most glyphs into each subset, so only the ones the app's CSS enables are kept.
 */
async function keptFeatures(font, enabled) {
  return [...await featureTags(font)].filter((tag) => !/^(cv\d\d|ss\d\d|salt|aalt)$/.test(tag) || enabled.includes(tag)).sort()
}

const fontFace = ([name, range]) =>
  `@font-face{font-family:"Inter";font-style:normal;font-weight:100 900;font-display:optional;src:url("./InterVariable-${name}.woff2") format("woff2");unicode-range:${range};}`

const mtime = (file) => {
  try {
    return statSync(file).mtimeMs
  } catch {
    return 0
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const enabled = enabledFeatures()
  const stamp = `/* Generated by scripts/subset-fonts.mjs; enabled alternates: ${enabled.join(' ')}. */`
  const fresh = mtime(css) > Math.max(mtime(source), mtime(fileURLToPath(import.meta.url))) && readFileSync(css, 'utf8').startsWith(stamp)
  if (fresh && Object.keys(subsets).every((name) => mtime(subsetFile(name)))) process.exit(0)
  mkdirSync(outDir, { recursive: true })
  const font = readFileSync(source)
  const keepFeatures = await keptFeatures(font, enabled)
  for (const [name, range] of Object.entries(subsets)) {
    writeFileSync(subsetFile(name), await subsetFont(font, rangeText(range), { targetFormat: 'woff2', keepFeatures }))
  }
  // Written last: its stamp and mtime mark a complete run.
  writeFileSync(css, `${stamp}\n${Object.entries(subsets).map(fontFace).join('\n')}\n`)
  console.log(`subset-fonts: wrote ${Object.keys(subsets).length} Inter subsets (alternates ${enabled.join(', ')})`)
}
